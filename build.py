def scene(root, slug):
    """Opening scenes of a project page: a side-by-side pair (an energy setting and a
    physical-AI setting of the same problem), stacked on phones. data/scenes.json:
    {"<slug>": {"pair": [{"file": "<slug>-energy.jpg", "alt": "...", "caption": "...", "position": "50% 50%"}, ...]}}
    The caption is a one-sentence key to what the painted overlays mean."""
    meta = SCENES.get(slug) or {}
    items = [it for it in meta.get("pair", []) if (SRC / "assets" / "img" / "scenes" / it["file"]).exists()]
    if not items:
        return f"<!-- scene {slug}: images not available yet -->"
    figs = []
    for it in items:
        pos = f' style="object-position:{esc(it["position"])}"' if it.get("position") else ""
        img = f'<img src="{root}assets/img/scenes/{esc(it["file"])}" alt="{esc(it["alt"])}" width="1200" height="900"{pos}>'
        cap = f'<p class="scene-cap">{esc(it["caption"])}</p>' if it.get("caption") else ""
        figs.append(f'<div class="scene-item">{img}{cap}</div>')
    return f'<figure class="scene scene-pair wrap">{"".join(figs)}</figure>'


DIAGRAM_SCALE = 1.6  # display a draw.io export at most this many CSS px per point


def size_diagrams(body):
    """Give every exported diagram its true aspect ratio and a legible maximum width.
    The draw.io exports (tools/diagrams/export.sh) record their size in points."""
    def dims(name):
        f = SRC / "assets" / "img" / "diagrams" / f"{name}.svg"
        if not f.exists():
            return None
        m = re.search(r'<svg[^>]*\bwidth="([\d.]+)"[^>]*\bheight="([\d.]+)"', f.read_text()[:600])
        return (float(m.group(1)), float(m.group(2))) if m else None

    def fix(m):
        tag, name = m.group(0), m.group(2)
        d = dims(name)
        if not d:
            return tag
        w, h = d
        tag = re.sub(r'\s(?:width|height)="[^"]*"', "", tag)
        # content hash in the URL: a redrawn diagram gets a new URL, so no browser shows a cached old one
        v = hashlib.sha1((SRC / "assets" / "img" / "diagrams" / f"{name}.svg").read_bytes()).hexdigest()[:8]
        tag = tag.replace(f"{name}.svg\"", f"{name}.svg?v={v}\"")
        extra = f' width="{round(w)}" height="{round(h)}"'
        if tag.startswith("<img"):
            tag = re.sub(r'\sstyle="[^"]*"', "", tag)
            extra += f' style="max-width:{round(w * DIAGRAM_SCALE)}px"'
        return tag[:-1].rstrip("/").rstrip() + extra + ">"
    return re.sub(r'<(img|source)\b[^>]*?(?:src|srcset)="[^"]*assets/img/diagrams/([\w-]+)\.svg"[^>]*>', fix, body)


def scene_mosaic(root, slugs):
    """Small preview tiles of the opening scenes of several project pages (home page)."""
    by_slug = {p["slug"]: p for p in PROJECTS}
    tiles = []
    for slug in slugs.split(","):
        for it in (SCENES.get(slug) or {}).get("pair", []):
            thumb = f"assets/img/scenes/thumbs/{it['file'].rsplit('.', 1)[0]}.webp"
            if not (SRC / thumb).exists():
                continue
            title = by_slug[slug]["title"] if slug in by_slug else slug
            tiles.append(f'<a href="{root}research/{slug}/" title="{esc(title)}"><img src="{root}{thumb}" alt="{esc(it["alt"])}" width="360" height="270" loading="lazy"></a>')
    return f'<div class="scene-mosaic">{"".join(tiles)}</div>' if tiles else ""


