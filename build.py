META_RE = re.compile(r"\A\s*<!--(.*?)-->\s*", re.S)


def parse_page(text):
    meta = {}
    m = META_RE.match(text)
    if m:
        for line in m.group(1).strip().splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip()] = v.strip()
        text = text[m.end():]
    return meta, text


def nav_html(active, root):
    items = []
    for key, label, url in NAV:
        cur = ' aria-current="page"' if key == active else ""
        items.append(f'<a href="{root}{url}"{cur}>{label}</a>')
    return "".join(items)


def page_icon(name):
    svg = (SRC / "_partials" / "icons" / f"{name}.svg").read_text().strip()
    return f'<span class="page-icon">{svg}</span>'


def partial(name):
    return (SRC / "_partials" / f"{name}.html").read_text()


def render(path):
    rel = path.relative_to(SRC)
    depth = len(rel.parts) - 1
    root = "../" * depth
    meta, body = parse_page(path.read_text())

    body = body.replace("{{pubs:selected}}", pubs_selected(root))
    body = body.replace("{{pubs:all}}", pubs_all(root))
    body = body.replace("{{projects:cards}}", project_cards(root))
    body = body.replace("{{projects:cards=current}}", project_cards(root, "core"))
    body = body.replace("{{news}}", news_list(root))
    body = re.sub(r"\{\{pubs:project=([\w-]+)\}\}", lambda m: pubs_for_project(root, m.group(1)), body)
    body = re.sub(r"\{\{projects:nav=([\w-]+)\}\}", lambda m: project_nav(root, m.group(1)), body)
    body = re.sub(r"\{\{software:project=([\w-]+)\}\}", lambda m: software_cards(root, m.group(1)), body)
    body = re.sub(r"\{\{scenes:mosaic=([\w,-]+)\}\}", lambda m: scene_mosaic(root, m.group(1)), body)
    body = re.sub(r"\{\{scene:([\w-]+)\}\}", lambda m: scene(root, m.group(1)), body)
    body = re.sub(r"\{\{bib:([\w-]+)\}\}", lambda m: bib_block(m.group(1)), body)
    body = re.sub(r"\{\{icon:([\w-]+)\}\}", lambda m: page_icon(m.group(1)), body)
    body = re.sub(r"\{\{diagram:([\w-]+)(?: focus=([\w,-]+))?\}\}", lambda m: diagram(m.group(1), m.group(2)), body)

    body = size_diagrams(body)

    url_path = "" if rel.as_posix() == "index.html" else rel.as_posix().removesuffix("index.html")
    page_title = meta.get("title", "Andrew Rosemberg")
    full_title = page_title if page_title.startswith("Andrew Rosemberg") else f"{page_title} · Andrew Rosemberg"
    extra_head = ""
    if meta.get("math") == "true":
        extra_head += partial("math")
    if meta.get("redirect"):  # a page that moved: forward to its new address and canonicalize there
        target = meta["redirect"]
        extra_head += f'<meta http-equiv="refresh" content="0; url={root}{target}">\n  <meta name="robots" content="noindex">\n'
        url_path = target
    if rel.as_posix() == "404.html":
        root = SITE_URL  # 404 is served from arbitrary depths

    head = partial("head")
    head = (head.replace("{{title}}", esc(full_title))
                .replace("{{description}}", esc(meta.get("description", "")))
                .replace("{{canonical}}", SITE_URL + url_path)
                .replace("{{og_image}}", SITE_URL + meta.get("image", "assets/img/social-preview.png"))
                .replace("{{extra_head}}", extra_head))
    header = partial("header").replace("{{nav}}", nav_html(meta.get("nav", ""), root))
    footer = partial("footer").replace("{{year}}", str(date.today().year)).replace(
        "{{updated}}", date.today().strftime("%B %Y"))
    page = head + header + f'<main id="main">{body}</main>' + footer
    page = page.replace("{{v:css}}", ASSET_VERSION["css"]).replace("{{v:js}}", ASSET_VERSION["js"])
    return page.replace("{{root}}", root), url_path, meta


def build():
    # Build into a fresh directory and swap it in, so a preview server never sees a
    # half-written site (and concurrent builds cannot delete each other's output).
    global OUT
    final, OUT = OUT, OUT.with_name(f"{OUT.name}.tmp-{os.getpid()}")
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    try:
        _build()
    except BaseException:
        shutil.rmtree(OUT, ignore_errors=True)
        raise
    old = final.with_name(f"{final.name}.old-{os.getpid()}")
    if final.exists():
        final.rename(old)
    OUT.rename(final)
    shutil.rmtree(old, ignore_errors=True)
    OUT = final


def _build():
    shutil.copytree(SRC / "assets", OUT / "assets")
    urls, pages = [], []
    for path in sorted(SRC.rglob("*.html")):
        if "_partials" in path.parts or "assets" in path.relative_to(SRC).parts:
            continue
        page, url_path, meta = render(path)
        dest = OUT / path.relative_to(SRC)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page)
        if path.name != "404.html" and meta.get("sitemap") != "false" and not meta.get("redirect"):
            urls.append(SITE_URL + url_path)
            pages.append((url_path, meta))
    write_search_index(pages)
    (OUT / ".nojekyll").write_text("")
    (OUT / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {SITE_URL}sitemap.xml\n")
    today = date.today().isoformat()
    (OUT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url><loc>{u}</loc><lastmod>{today}</lastmod></url>\n" for u in urls)
        + "</urlset>\n")
    print(f"Built {len(urls)} pages into _site/")


def write_search_index(pages):
    """Entries for the quick-search palette (assets/search.json)."""
    items = []
    for url_path, meta in pages:
        items.append({"type": "Page", "title": meta.get("title", "Home").split(" — ")[0],
                      "meta": meta.get("description", "")[:140], "url": url_path})
