#!/usr/bin/env python3
"""Build the static website from ``src/`` and ``data/`` into ``_site/``.

No third-party dependencies: run ``python3 build.py`` and open ``_site/index.html``,
or ``python3 build.py --serve`` to preview at http://localhost:8000/.

Pages are plain HTML files in ``src/`` that start with a metadata comment::

    <!--
    title: Page title
    description: One sentence for search engines and link previews.
    nav: research
    -->

and may use these tokens:

    {{root}}                 relative path to the site root ("", "../", ...)
    {{pubs:selected}}        selected publications (data/publications.json)
    {{pubs:all}}             full publication list, grouped by year
    {{pubs:project=<slug>}}  publications attached to one project
    {{bib:<id>}}             BibTeX block for one publication
    {{projects:cards}}       research cards (data/projects.json)
    {{projects:nav=<slug>}}  theory, software, paper, and related-project links
    {{news}}                 news list (data/news.json)
    {{software:project=<slug>}}
                             feature cards of the packages behind a project (data/software.json)
    {{scenes:mosaic=<slug>,<slug>}}
                             small preview tiles of those pages' opening scenes (home page)
    {{scene:<slug>}}         opening scene pair of a project page (src/assets/img/scenes/, alt text
                             and focal points in data/scenes.json)
    {{diagram:<name> focus=<part>,<part>}}
                             inline decision-process diagram from src/_partials/diagrams/
                             (generated by tools/make_diagrams.js); the listed parts are
                             highlighted and the rest of the structure is subdued
"""

