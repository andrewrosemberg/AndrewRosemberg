def card_image(pr, root):
    alt = esc(pr["thumb_alt"])
    if pr.get("anim"):  # animated card art, with a still frame for reduced motion
        return (f'<picture><source srcset="{root}{esc(pr["still"])}" media="(prefers-reduced-motion: reduce)">'
                f'<img src="{root}{esc(pr["anim"])}" alt="{alt}" loading="lazy"></picture>')
    return f'<img src="{root}{esc(pr["thumb"])}" alt="{alt}" loading="lazy">'


def project_card(pr, root):
    ext = pr["href"].startswith("http")
    tags = "".join(f'<li>{esc(t)}</li>' for t in pr.get("tags", []) if t != pr.get("role"))
    go = "Paper website" if ext else "Project page"
    arrow = "↗" if ext else "→"
    role = f'<p class="card-role area-{esc(pr["area"])}">{esc(pr["role"])}</p>' if pr.get("role") else ""
    return (
        f'<article class="project-card{" featured" if pr.get("featured") else ""}">'
        f'<a class="card-link" href="{esc(href(pr["href"], root))}">'
        f'<div class="card-media">{card_image(pr, root)}</div>'
        f'<div class="card-body">{role}<p class="card-venue">{esc(pr["venue"])}</p>'
        f'<h3>{esc(pr["title"])}</h3><p class="card-summary">{esc(pr["summary"])}</p>'
        f'<ul class="tags" aria-label="Topics">{tags}</ul>'
        f'<span class="card-go">{go} <span aria-hidden="true">{arrow}</span></span></div></a></article>'
    )


def project_cards(root, only=None):
    """Current work (the "core" group, featured first), then the remaining projects."""
    core = [p for p in PROJECTS if p.get("group") == "core"]
    grid = '<div class="project-grid">' + "".join(project_card(p, root) for p in core) + "</div>"
    if only == "core":
        return grid
    rest = [p for p in PROJECTS if p.get("group") != "core"]
    return grid + '<div class="project-grid four more">' + "".join(project_card(p, root) for p in rest) + "</div>"


