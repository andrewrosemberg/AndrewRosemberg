def pub_links(p, root):
    links = []
    for key, label in LINK_LABELS:
        url = p.get("links", {}).get(key)
        if not url:
            continue
        ext = url.startswith("http")
        lab = p.get("link_labels", {}).get(key, label)
        arrow = ' <span aria-hidden="true">↗</span>' if ext and key not in ("site",) else ""
        cls = "pub-link primary" if key in ("site", "page") else "pub-link"
        links.append(f'<a class="{cls}" href="{esc(href(url, root))}">{esc(lab)}{arrow}</a>')
    if p.get("bibtex"):
        links.append(
            '<details class="bib"><summary class="pub-link">BibTeX</summary>'
            f'<div class="bib-box"><button class="copy-bib" type="button">Copy</button>'
            f'<pre><code>{esc(p["bibtex"])}</code></pre></div></details>'
        )
    return f'<div class="pub-links">{"".join(links)}</div>'


def pub_item(p, root, thumb=False):
    venue = esc(p["venue"])
    badge = f'<span class="venue-badge {esc(p.get("type", ""))}">{esc(p["badge"])}</span>' if p.get("badge") else ""
    note = f'<p class="pub-note">{p["note"]}</p>' if p.get("note") else ""
    img = ""
    if thumb and not p.get("thumb"):
        icon = (SRC / "_partials" / "icons" / "publications.svg").read_text().strip()
        img = f'<span class="pub-thumb placeholder" aria-hidden="true">{icon}</span>'
    if thumb and p.get("thumb"):
        img = (f'<a class="pub-thumb" href="{esc(href(p["links"].get("site") or p["links"].get("page") or "#", root))}" tabindex="-1" aria-hidden="true">'
               f'<img src="{root}{esc(p["thumb"])}" alt="" loading="lazy" width="320" height="200"></a>')
    title = esc(p["title"])
    main = p.get("links", {}).get("site") or p.get("links", {}).get("page")
    if main:
        title = f'<a href="{esc(href(main, root))}">{title}</a>'
    return (
        f'<li class="pub{" has-thumb" if img else ""}" data-type="{esc(p.get("type", ""))}">{img}'
        f'<div class="pub-body"><p class="pub-meta">{badge}<span>{venue}</span></p>'
        f'<h3 class="pub-title">{title}</h3>'
        f'<p class="pub-authors">{authors_html(p["authors"])}</p>{note}{pub_links(p, root)}</div></li>'
    )


def pubs_selected(root):
    items = [p for p in PUBS if p.get("selected")]
    return '<ol class="pub-list selected">' + "".join(pub_item(p, root, thumb=True) for p in items) + "</ol>"


def pubs_all(root):
    years = {}
    for p in PUBS:
        years.setdefault(p["year"], []).append(p)
    parts = []
    for y in sorted(years, reverse=True):
        parts.append(
            f'<section class="pub-year" aria-labelledby="y{y}"><h2 class="year-label" id="y{y}">{y}</h2>'
            f'<ol class="pub-list">{"".join(pub_item(p, root, thumb=True) for p in years[y])}</ol></section>'
        )
    return "".join(parts)


def pubs_for_project(root, slug):
    here = f"research/{slug}/"
    items = []
    for p in PUBS:
        if slug in p.get("projects", []):
            q = dict(p, links={k: v for k, v in p.get("links", {}).items() if v != here})
            items.append(q)
    return '<ol class="pub-list compact">' + "".join(pub_item(p, root) for p in items) + "</ol>"


