def href(url, root):
    """Internal links are written relative to the site root."""
    if url.startswith(("http://", "https://", "mailto:", "#")):
        return url
    return root + url


def authors_html(authors):
    out = []
    for a in authors:
        name = esc(a.rstrip("*")).replace(" ", "&nbsp;")
        if a.rstrip("*") in (ME, "Andrew Rosemberg", "Andrew D. W. Rosemberg"):
            name = f'<strong class="me">{name}</strong>'
        out.append(name)
    return ", ".join(out)


